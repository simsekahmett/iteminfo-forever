#!/usr/bin/env python3
"""Builds ItemInfo's static data files (Data/*.lua).

Sources, read from a local AddOns folder (nothing is needed at runtime):
  * AtlasLootContinued/Data/Profession.lua, Recipe.lua  -> recipes (GPL-2.0)
  * QuestieDB/QuestieDB_Forever.toc (or _Camelot)        -> vendors, drops, NPCs, quests
  * AtlasLootContinued_DungeonsAndRaids/droprate.lua     -> drop rates of bosses (GPL-2.0)

Usage: gen_data.py <AddOns dir> <output Data dir>
Requires: pip install cbor2
"""
import base64
import re
import sys
import zlib
from pathlib import Path

import cbor2

addons = Path(sys.argv[1])
out = Path(sys.argv[2])
out.mkdir(parents=True, exist_ok=True)

HEADER = "-- GENERATED by tools/gen_data.py. Do not edit, run the tool again.\n"

# ---------------------------------------------------------------- AtlasLoot


def block(text, start_marker):
    """Returns the body of the table opened by 'start_marker'."""
    start = text.index(start_marker)
    start = text.index("{", start)
    depth, i = 0, start
    while True:
        c = text[i]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return text[start + 1:i]
        i += 1


SPELL_RE = re.compile(
    r"^\s*\[(\d+)\]\s*=\s*\{\s*(nil|\d+),\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+),"
    r"\s*\{([^}]*)\},\s*\{([^}]*)\}(?:,\s*(\d+))?\s*\}", re.M)
RECIPE_RE = re.compile(r"^\s*\[(\d+)\]\s*=\s*\{\s*(\d+),\s*(\d+),\s*(\d+)\s*\}", re.M)


def ints(s):
    return [int(x) for x in re.findall(r"\d+", s)]


prof_text = (addons / "AtlasLootContinued/Data/Profession.lua").read_text(encoding="utf-8")
recipe_text = (addons / "AtlasLootContinued/Data/Recipe.lua").read_text(encoding="utf-8")


def parse_spells(marker):
    spells = {}
    for m in SPELL_RE.finditer(block(prof_text, marker)):
        spell, item, prof, skill, low, high, reagents, counts, made = m.groups()
        reagents, counts = ints(reagents), ints(counts)
        if len(reagents) != len(counts):
            raise SystemExit(f"reagent mismatch for spell {spell}")
        spells[int(spell)] = {
            "item": 0 if item == "nil" else int(item),
            "prof": int(prof), "skill": int(skill), "low": int(low), "high": int(high),
            "reagents": list(zip(reagents, counts)), "made": int(made) if made else 1,
        }
    return spells


classic = parse_spells("PROFESSION_DATA.CLASSIC = {")
forever = parse_spells("PROFESSION_DATA.FOREVER = {")
forever.update(parse_spells("PROFESSION_DATA.FOREVER_HEALING_POTIONS = {"))

# Forever re-numbered some spells, the Classic spell creating the same item is stale
replaced = {s["item"] for s in forever.values() if s["item"]}
spells = {k: v for k, v in classic.items() if v["item"] not in replaced}
spells.update(forever)

recipe_items = {}
for marker in ("RECIPE_DATA.CLASSIC = {", "RECIPE_DATA.FOREVER = {"):
    for m in RECIPE_RE.finditer(block(recipe_text, marker)):
        item, prof, rank, spell = map(int, m.groups())
        if spell and spell in spells:
            recipe_items[item] = spell

# ----------------------------------------------------------------- Questie

meta = {}
questie_toc = next(p for p in (addons / "QuestieDB/QuestieDB_Forever.toc",
                               addons / "QuestieDB/QuestieDB_Camelot.toc") if p.exists())
with open(questie_toc, encoding="utf-8") as f:
    for line in f:
        if line.startswith("## X-"):
            key, _, value = line[3:].rstrip("\n").partition(": ")
            meta[key] = value


def stored(key):
    value = meta.get(key)
    if value is None:
        return None
    m = re.fullmatch(r"~(\d+)~", value)
    if m:
        value = "".join(meta[f"{key}-{i}"] for i in range(1, int(m.group(1)) + 1))
    return value


def decode(key, compressed=False):
    value = stored(key)
    if value is None:
        return None
    raw = base64.b64decode(value)
    if compressed:
        raw = zlib.decompress(raw)
    return cbor2.loads(raw)


def txt(value):
    return value.decode("utf-8") if isinstance(value, bytes) else (value or "")


def ids(entity):
    return decode(f"X-{entity}-IDS", compressed=True)


ITEM_NAME, ITEM_NPC_DROPS, ITEM_CLASS, ITEM_VENDORS = 1, 2, 12, 14
NPC_NAME, NPC_SPAWNS, NPC_ZONE, NPC_FRIENDLY = 1, 7, 9, 13

item_ids = set(ids("Item"))
npc_ids = set(ids("Npc"))

vendors = {}       # itemId -> [npcId]
drops = {}         # itemId -> ([npcId], total)
# Items dropped by more creatures are world drops, their creatures are not listed
MAX_DROPS = 20

for item in sorted(item_ids):
    sold = decode(f"X-Item-{item}-{ITEM_VENDORS}")
    if sold:
        sold = sorted(n for n in sold if n in npc_ids)
        if sold:
            vendors[item] = sold

for item in sorted(item_ids):
    dropped = decode(f"X-Item-{item}-{ITEM_NPC_DROPS}")
    if dropped:
        dropped = sorted(n for n in dropped if n in npc_ids)
        if dropped:
            drops[item] = (dropped if len(dropped) <= MAX_DROPS else [], len(dropped))

# Quests rewarding an item, and what is shown of each quest
ITEM_QUEST_REWARDS = 6
QUEST_NAME, QUEST_STARTED_BY, QUEST_REQUIRED_LEVEL, QUEST_LEVEL = 1, 2, 4, 5
QUEST_RACES, QUEST_ZONE = 6, 17
ALLIANCE_RACES, HORDE_RACES = 77, 178

quest_ids = set(ids("Quest"))
quest_rewards = {}  # itemId -> [questId]

for item in sorted(item_ids):
    rewarded = decode(f"X-Item-{item}-{ITEM_QUEST_REWARDS}")
    if rewarded:
        rewarded = sorted(q for q in rewarded if q in quest_ids)
        if rewarded:
            quest_rewards[item] = rewarded


# Quests asking for an item, from their objectives: { 3: [[itemId, text, ...]] }
QUEST_OBJECTIVES, OBJECTIVE_ITEMS = 10, 3
quest_objectives = {}  # itemId -> [questId]

for quest in sorted(quest_ids):
    objectives = decode(f"X-Quest-{quest}-{QUEST_OBJECTIVES}")
    if isinstance(objectives, list):
        objectives = {i + 1: v for i, v in enumerate(objectives)}
    wanted = (objectives or {}).get(OBJECTIVE_ITEMS) or []
    for objective in wanted:
        if isinstance(objective, list) and objective and objective[0] in item_ids:
            quest_objectives.setdefault(objective[0], set()).add(quest)
quest_objectives = {item: sorted(qs) for item, qs in quest_objectives.items()}


def as_row(value):
    """Returns a stored row as a table of field indices."""
    if isinstance(value, list):
        return {i + 1: v for i, v in enumerate(value)}
    return value or {}


def faction_of(races):
    # Masks of all races are stored with a flag above the 32nd bit
    races = (races or 0) & 0xFFFFFFFF
    alliance, horde = races & ALLIANCE_RACES, races & HORDE_RACES
    if alliance and not horde:
        return "A"
    if horde and not alliance:
        return "H"
    return ""


quests = {}  # questId -> (name, level, requiredLevel, faction, areaId, starterNpcId)
for quest in sorted({q for qs in list(quest_rewards.values()) + list(quest_objectives.values()) for q in qs}):
    row = as_row(decode(f"X-Quest-{quest}-S"))
    starters = decode(f"X-Quest-{quest}-{QUEST_STARTED_BY}")
    if isinstance(starters, dict):
        starters = [starters.get(1)]
    starter_npcs = starters[0] if starters and starters[0] else []
    starter = next((n for n in starter_npcs if n in npc_ids), 0)
    zone = row.get(QUEST_ZONE) or 0
    quests[quest] = (
        txt(row.get(QUEST_NAME)), row.get(QUEST_LEVEL) or 0, row.get(QUEST_REQUIRED_LEVEL) or 0,
        faction_of(row.get(QUEST_RACES)), zone if zone > 0 else 0, starter,
    )

used_npcs = set(q[5] for q in quests.values() if q[5])
for sold in vendors.values():
    used_npcs.update(sold)
for dropped, _ in drops.values():
    used_npcs.update(dropped)

# The places a creature that drops something spawns at in its zone, points
# close to one another merged, so that the map shows where it roams
MAX_SPAWNS, SPAWN_DISTANCE = 10, 4.0
drop_npcs = {n for dropped, _ in drops.values() for n in dropped}
spawns_of = {}  # npcId -> [(x, y)], the first being the one of 'npcs'


def merge_points(points):
    points = [p for p in points if isinstance(p, list) and len(p) >= 2
              and p[0] is not None and p[1] is not None and p[0] >= 0 and p[1] >= 0]
    chosen = []
    # The first point stays first, the farthest from those chosen comes next
    while points and len(chosen) < MAX_SPAWNS:
        if not chosen:
            best = points[0]
        else:
            best = max(points, key=lambda p: min((p[0] - c[0]) ** 2 + (p[1] - c[1]) ** 2 for c in chosen))
            if min((best[0] - c[0]) ** 2 + (best[1] - c[1]) ** 2 for c in chosen) < SPAWN_DISTANCE ** 2:
                break
        chosen.append((best[0], best[1]))
    return chosen


npcs = {}
for npc in sorted(used_npcs):
    row = decode(f"X-Npc-{npc}-S") or {}
    if isinstance(row, list):  # a Lua array, i.e. field indices 1..n
        row = {i + 1: v for i, v in enumerate(row)}
    spawns = decode(f"X-Npc-{npc}-{NPC_SPAWNS}") or {}
    if isinstance(spawns, list):  # a Lua array, i.e. zone IDs 1..n
        spawns = {i + 1: v for i, v in enumerate(spawns) if v}
    spawns = {z: v for z, v in spawns.items() if isinstance(v, list) and v}
    zone = row.get(NPC_ZONE) or 0
    if (not zone or zone not in spawns) and spawns:
        zone = max(spawns, key=lambda z: len(spawns[z]))
    x = y = -1
    points = spawns.get(zone)
    if points and isinstance(points[0], list) and points[0][0] is not None and points[0][0] >= 0:
        x, y = points[0][0], points[0][1]
    npcs[npc] = (txt(row.get(NPC_NAME)), zone or 0, x, y, txt(row.get(NPC_FRIENDLY)))
    if npc in drop_npcs and points:
        spread = merge_points(points)
        if len(spread) > 1:
            spawns_of[npc] = spread

# Localized NPC names: one compressed column block per locale, aligned with the ID list
LOCALES = ["deDE", "esES", "esMX", "frFR", "koKR", "ptBR", "ruRU", "zhCN", "zhTW"]
npc_id_list = ids("Npc")
quest_id_list = ids("Quest")
quest_names = {}
for locale in LOCALES:
    names = {}
    blk = decode(f"X-l10n-{locale}-Quest", compressed=True)
    if blk is not None:
        for index, name in enumerate(blk[0]):
            quest = quest_id_list[index]
            if quest in quests and name and txt(name) != quests[quest][0]:
                names[quest] = txt(name)
    quest_names[locale] = names
npc_names = {}
for locale in LOCALES:
    names = {}
    blk = decode(f"X-l10n-{locale}-Npc", compressed=True)
    if blk is not None:
        # The first column holds the names, as a list aligned with the ID list
        for index, name in enumerate(blk[0]):
            npc = npc_id_list[index]
            if npc in npcs and name and txt(name) != npcs[npc][0]:
                names[npc] = txt(name)
    npc_names[locale] = names

# ------------------------------------------------------------ Drop rates

# AtlasLoot knows the drop rates of the bosses of dungeons and raids:
# [npcId] = { [itemId] = percent, ... }
drop_rates = {}  # itemId -> [(npcId, percent)]
rate_file = addons / "AtlasLootContinued_DungeonsAndRaids/droprate.lua"
if rate_file.exists():
    rate_text = rate_file.read_text(encoding="utf-8-sig")
    rate_text = rate_text[rate_text.index("local DropRateData"):rate_text.index("--##END-DATA##")]
    npc = None
    for line in rate_text.splitlines():
        m = re.match(r"\s*\[(\d+)\]\s*=\s*\{\s*$", line)
        if m:
            npc = int(m.group(1))
            continue
        m = re.match(r"\s*\[(\d+)\]\s*=\s*([\d.]+)", line)
        if m and npc is not None:
            item, rate = int(m.group(1)), float(m.group(2))
            if item in drops and npc in drops[item][0]:
                drop_rates.setdefault(item, []).append((npc, rate))

# ------------------------------------------------------------------ Output


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def num(v):
    return str(int(v)) if float(v).is_integer() else f"{v:.1f}"


with open(out / "Recipes.lua", "w", encoding="utf-8", newline="\n") as f:
    f.write(HEADER)
    f.write("-- Recipe data derived from AtlasLootClassic (GPL-2.0), see NOTICE.md.\n")
    f.write("local _, ns = ...\n\n")
    f.write("-- [spellId] = { createdItemId (0: none, e.g. an enchant), profession, skill,\n")
    f.write("--              yellowAt, greenAt, { reagentId, count, ... }, createdCount }\n")
    f.write("ns.Data.spells = {\n")
    for spell in sorted(spells):
        s = spells[spell]
        reagents = ",".join(f"{i},{c}" for i, c in s["reagents"])
        made = f",{s['made']}" if s["made"] != 1 else ""
        f.write(f"[{spell}]={{{s['item']},{s['prof']},{s['skill']},{s['low']},{s['high']},"
                f"{{{reagents}}}{made}}},\n")
    f.write("}\n\n-- [recipeItemId] = spellId taught\nns.Data.recipeItems = {\n")
    for item in sorted(recipe_items):
        f.write(f"[{item}]={recipe_items[item]},\n")
    f.write("}\n")

with open(out / "Sources.lua", "w", encoding="utf-8", newline="\n") as f:
    f.write(HEADER)
    f.write("-- Vendor, drop and NPC data derived from QuestieDB, see NOTICE.md.\n")
    f.write("local _, ns = ...\n\n-- [itemId] = { vendorNpcId, ... }\nns.Data.vendors = {\n")
    for item in sorted(vendors):
        f.write(f"[{item}]={{{','.join(map(str, vendors[item]))}}},\n")
    f.write("}\n\n-- [itemId] = { total, npcId, ... }, the NPCs are only listed for at most "
            f"{MAX_DROPS}\nns.Data.drops = {{\n")
    for item in sorted(drops):
        listed, total = drops[item]
        f.write(f"[{item}]={{{','.join(map(str, [total] + listed))}}},\n")
    f.write("}\n\n-- [npcId] = { name (enUS), areaId, x, y, friendlyTo }\nns.Data.npcs = {\n")
    for npc in sorted(npcs):
        name, zone, x, y, friendly = npcs[npc]
        f.write(f"[{npc}]={{{lua_str(name)},{zone},{num(x)},{num(y)},{lua_str(friendly)}}},\n")
    f.write("}\n\n-- [npcId] = { x, y, ... } where else in its zone a creature spawns, the first\n"
            "-- point being the one above\nns.Data.spawns = {\n")
    for npc in sorted(spawns_of):
        f.write(f"[{npc}]={{{','.join(num(v) for p in spawns_of[npc] for v in p)}}},\n")
    f.write("}\n\n-- [itemId] = { npcId, percent, ... } the drop rates known, of bosses (AtlasLoot)\n"
            "ns.Data.dropRates = {\n")
    for item in sorted(drop_rates):
        f.write(f"[{item}]={{{','.join(f'{n},{num(r) if r >= 10 else round(r, 2)}' for n, r in sorted(drop_rates[item]))}}},\n")
    f.write("}\n")

with open(out / "NpcNames.lua", "w", encoding="utf-8", newline="\n") as f:
    f.write(HEADER)
    f.write("-- Localized NPC names derived from QuestieDB, see NOTICE.md.\n")
    f.write("local _, ns = ...\n\nlocal locale = GetLocale()\n")
    for locale in LOCALES:
        names = npc_names[locale]
        if not names:
            continue
        f.write(f'\nif locale == "{locale}" then\nns.Data.npcNames = {{\n')
        for npc in sorted(names):
            f.write(f"[{npc}]={lua_str(names[npc])},\n")
        f.write("}\nend\n")

with open(out / "Quests.lua", "w", encoding="utf-8", newline="\n") as f:
    f.write(HEADER)
    f.write("-- Quest data derived from QuestieDB, see NOTICE.md.\n")
    f.write("local _, ns = ...\n\n-- [itemId] = { questId, ... } rewarding it\nns.Data.questRewards = {\n")
    for item in sorted(quest_rewards):
        f.write(f"[{item}]={{{','.join(map(str, quest_rewards[item]))}}},\n")
    f.write("}\n\n-- [itemId] = { questId, ... } asking for it\nns.Data.questObjectives = {\n")
    for item in sorted(quest_objectives):
        f.write(f"[{item}]={{{','.join(map(str, quest_objectives[item]))}}},\n")
    f.write("}\n\n-- [questId] = { name (enUS), level, requiredLevel, faction ('A', 'H' or ''),\n")
    f.write("--              areaId (0: none), starterNpcId (0: none) }\nns.Data.quests = {\n")
    for quest in sorted(quests):
        name, level, required, faction, zone, starter = quests[quest]
        f.write(f"[{quest}]={{{lua_str(name)},{level},{required},{lua_str(faction)},{zone},{starter}}},\n")
    f.write("}\n\nlocal locale = GetLocale()\n")
    for locale in LOCALES:
        names = quest_names[locale]
        if not names:
            continue
        f.write(f'\nif locale == "{locale}" then\nns.Data.questNames = {{\n')
        for quest in sorted(names):
            f.write(f"[{quest}]={lua_str(names[quest])},\n")
        f.write("}\nend\n")

print(f"items rewarded by quests: {len(quest_rewards)}, quests: {len(quests)}; localized: "
      + ", ".join(f"{k}={len(v)}" for k, v in quest_names.items()))
print(f"items quests ask for: {len(quest_objectives)}; creatures with more spawns: {len(spawns_of)}; "
      f"items with drop rates: {len(drop_rates)}")
print(f"spells: {len(spells)} ({sum(1 for s in spells.values() if not s['item'])} without item)")
print(f"recipe items: {len(recipe_items)}")
print(f"items with vendors: {len(vendors)}, items with drops: {len(drops)} ({sum(1 for l, _ in drops.values() if not l)} world drops)")
print(f"npcs: {len(npcs)}; localized: " + ", ".join(f"{k}={len(v)}" for k, v in npc_names.items()))
